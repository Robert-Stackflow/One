import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {join,resolve} from 'node:path';
import {mkdir,writeFile} from 'node:fs/promises';
const run=promisify(execFile),folder=resolve('work/current/theme-location/native-build');
await mkdir(folder,{recursive:true});await mkdir('dist/native',{recursive:true});
const vswhere=join(process.env['ProgramFiles(x86)']||'C:\\Program Files (x86)','Microsoft Visual Studio/Installer/vswhere.exe');
const {stdout}=await run(vswhere,['-latest','-products','*','-requires','Microsoft.VisualStudio.Component.VC.Tools.x86.x64','-property','installationPath'],{windowsHide:true});
const installation=stdout.trim();if(!installation)throw Error('需要 Visual Studio C++ 工具链构建定位服务');
const script=join(folder,'location.cmd');
await writeFile(script,`@echo off\r\ncall "${installation}\\VC\\Auxiliary\\Build\\vcvars64.bat" >nul\r\nif errorlevel 1 exit /b 1\r\ncl /nologo /std:c++20 /EHsc /MT /O2 /utf-8 /DUNICODE /D_UNICODE /LD "${resolve('native/location.cpp')}" /Fe:"${resolve('dist/native/One.Location.dll')}" /Fo:"${join(folder,'location.obj')}" /link windowsapp.lib ole32.lib /IMPLIB:"${join(folder,'One.Location.lib')}"\r\n`);
await run('cmd.exe',['/d','/c',script],{windowsHide:true,maxBuffer:65536});
console.log('Windows location bridge built.');
