import './search.css';
import './styles.css';
import './scrollbars.css';
import './refinement.css';
import './selection.css';
import './interface-refinement.css';
import './components.css';
import {setupAppearance} from './appearance';
import {setupTextSelection} from './selection';
import {setupTooltips} from './tooltip';
import {setupSegments} from './segments';
import {setupWindowVisibility} from './window-visibility';
import {api} from './ui';
const view=new URLSearchParams(location.search).get('view')||'main';
if(view!=='native-tooltip'){setupAppearance();setupTextSelection();setupTooltips();setupSegments();}
window.addEventListener('error',event=>{void api.diagnosticsReport('uncaught-error',event.error?.stack||`${event.message} at ${event.filename}:${event.lineno}:${event.colno}`).catch(()=>{});});
window.addEventListener('unhandledrejection',event=>{const reason=event.reason;void api.diagnosticsReport('unhandled-rejection',reason?.stack||String(reason)).catch(()=>{});});
if(['main','file-action','preview','picker','search','color-editor','dialog-bar','archive-task'].includes(view))setupWindowVisibility();
const render=async()=>{
  if(view==='recognition')await (await import('./recognition-view')).renderRecognition();
  else if(view==='scroll-capture')(await import('./scroll-capture-view')).renderScrollCapture();
  else if(view==='capture')(await import('./capture-window-view')).renderCapture();
  else if(view==='native-tooltip')(await import('./native-tooltip-view')).renderNativeTooltip();
  else if(view==='echo')(await import('./hud')).renderHUD();
 else if(view==='color-picker')await (await import('./color-view')).renderColorPicker();
 else if(view==='color-zoom')await (await import('./color-zoom-view')).renderColorZoom();
 else if(view==='barcode-capture')await (await import('./barcode-capture-view')).renderBarcodeCapture();
 else if(view==='color-freeze')await (await import('./color-freeze-view')).renderColorFreeze();
 else if(view==='screen-ruler')(await import('./screen-ruler-view')).renderScreenRuler();
 else if(view==='color-editor')(await import('./color-editor-view')).renderColorEditor();
 else if(view==='command-confirm')await (await import('./menu-confirmation-view')).renderMenuConfirmation();
 else if(view==='preview')await (await import('./preview-view')).renderPreview();
 else if(view==='picker')(await import('./picker-view')).renderPicker();
 else if(view==='file-action')await (await import('./file-action-view')).renderFileAction();
 else if(view==='archive-task')await (await import('./archive-task-view')).renderArchiveTask();
 else if(view==='search-menu')await (await import('./search-menu')).renderSearchMenu();
 else if(view==='tray-menu')await (await import('./tray-menu-view')).renderTrayMenu();
 else if(view==='file-context')await (await import('./file-context-view')).renderFileContextMenu();
 else if(view==='dialog-bar')await (await import('./dialog-bar-view')).renderDialogBar();
 else if(view==='search')await (await import('./search-view')).renderSearch();
 else if(view==='ai-chat')await (await import('./ai-chat-view')).renderAIChat();
 else if(view==='pin'||view==='pin-controls')void import('./pin-window-view').then(m=>m.renderPinWindow(view==='pin-controls'));
else if(view==='image-editor')await (await import('./image-editor-view')).renderImageEditor();
 else (await import('./main-view')).renderMain();
};
void render().catch(error=>{void api.diagnosticsReport('render',error?.stack||String(error)).catch(()=>{});console.error(error);});
