const assert=require('node:assert/strict'),path=require('node:path');
const {expect}=require('@playwright/test');

module.exports=async function interactions(page,files){
 await page.evaluate(()=>{window.xlsxCopies=[];Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async text=>window.xlsxCopies.push(text)}});});
 await page.evaluate(file=>window.one.selectPreview(file),path.join(files,'zzz-interactions.xlsx'));
 await expect(page.locator('.xlsx-preview')).toHaveAttribute('data-state','ready');
 const grid=page.getByRole('region',{name:/Spreadsheet viewport/});
 const box=await grid.boundingBox();assert.ok(box&&box.width>500&&box.height>300);
 const copy=async()=>{const count=await page.evaluate(()=>window.xlsxCopies.length);await page.keyboard.press('Control+c');await page.waitForFunction(n=>window.xlsxCopies.length>n,count);return page.evaluate(()=>window.xlsxCopies.at(-1));};
 const cell=async(x,y)=>{await page.mouse.click(box.x+x,box.y+y);return copy();};
 const state=()=>page.evaluate(()=>({left:document.querySelector('[aria-label^="Spreadsheet viewport"]').scrollLeft,top:document.querySelector('[aria-label^="Spreadsheet viewport"]').scrollTop}));
 assert.equal(await cell(100,35),'CELL_1_1');
 assert.equal(await cell(300,55),'CELL_2_2');
 await page.keyboard.press('ArrowDown');assert.equal(await copy(),'CELL_4_2','keyboard skips hidden row 3');
 await page.keyboard.press('ArrowRight');assert.equal(await copy(),'CELL_4_4','keyboard skips hidden column C');
 assert.equal(await cell(300,75),'CELL_4_2','hidden row 3 takes no visible space');
 assert.equal(await cell(360,75),'CELL_4_4','hidden column C takes no visible space');
 assert.equal(await cell(300,75),'CELL_4_2');
 await page.keyboard.press('ArrowDown');assert.equal(await copy(),'CELL_5_2');
 await page.keyboard.press('ArrowUp');await page.keyboard.press('ArrowLeft');assert.equal(await copy(),'CELL_4_1');
 await page.keyboard.press('ArrowRight');assert.equal(await copy(),'CELL_4_2');
 await page.keyboard.type('123');await page.keyboard.press('Delete');
 await grid.evaluate(el=>{const data=new DataTransfer();data.setData('text/plain','REPLACEMENT');el.dispatchEvent(new ClipboardEvent('paste',{clipboardData:data,bubbles:true,cancelable:true}));});
 assert.equal(await copy(),'CELL_4_2','typing, deletion and paste preserve workbook contents');
 const before=await state();assert.equal(await cell(100,35),'CELL_1_1');
 await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.wheel(450,300);
 await expect.poll(async()=>{const s=await state();return s.left>before.left&&s.top>before.top;}).toBe(true);
 const after=await state();assert.equal(await cell(100,35),'CELL_1_1','frozen corner remains reachable after both-axis scrolling');
 const visible=await cell(Math.min(500,box.width-50),Math.min(300,box.height-50));
 const match=/^CELL_(\d+)_(\d+)$/.exec(visible);assert.ok(match,`scrolled cell is readable: ${visible}`);
 assert.ok(Number(match[1])>10&&Number(match[2])>4,'wheel reveals later rows and columns');
 await page.evaluate(file=>window.one.selectPreview(file),path.join(files,'daily.xlsx'));
 await expect(page.locator('.xlsx-preview')).toHaveAttribute('data-state','ready');
 return {keyboardCopy:['CELL_4_2','CELL_5_2','CELL_4_2'],hiddenRow:3,hiddenColumn:'C',wheel:{left:after.left,top:after.top},frozenCorner:'CELL_1_1'};
};
