const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const {spawnSync}=require('node:child_process');
const {_electron:electron,expect}=require('@playwright/test');
const {build}=require('esbuild');

async function main(){
 await fs.mkdir('work/temp',{recursive:true});
 const root=await fs.mkdtemp(path.resolve('work/temp/one-archive-launch-'));
 let app;
 try{
  const prefs=path.join(root,'preferences.cjs'),launch=path.join(root,'launch.cjs');
  await build({entryPoints:['src/shared/settings.ts'],outfile:prefs,bundle:true,platform:'node'});
  await build({entryPoints:['src/main/archive-launch.ts'],outfile:launch,bundle:true,platform:'node'});
  const {defaultSettings,validateSettings,mergeSettings}=require(prefs),{archiveLaunchPath}=require(launch);
  const old=defaultSettings();delete old.archive;
  assert.deepEqual(validateSettings(old).archive,defaultSettings().archive);
  const legacy=defaultSettings();delete legacy.archive.conflict;assert.equal(validateSettings(legacy).archive.conflict,'rename');
  assert.throws(()=>mergeSettings(defaultSettings(),{archive:{doubleClick:'delete'}}));
  assert.throws(()=>mergeSettings(defaultSettings(),{archive:{openCompleted:'true'}}));
  assert.throws(()=>mergeSettings(defaultSettings(),{archive:{defaultFormat:'rar'}}));
  assert.throws(()=>mergeSettings(defaultSettings(),{archive:{conflict:'erase'}}));
  const backed=mergeSettings(defaultSettings(),{archive:{doubleClick:'browse',defaultFormat:'7z',openCompleted:true,conflict:'skip'}});
  assert.deepEqual(validateSettings(JSON.parse(JSON.stringify(backed))).archive,backed.archive);
  assert.equal(archiveLaunchPath(['One.exe','--one-login-startup']),undefined);
  assert.equal(archiveLaunchPath(['One.exe','--one-archive=D:\\压缩 测试\\test.7z.001']),'D:\\压缩 测试\\test.7z.001');
  for(const args of [['--one-archive=relative.zip'],['--one-archive=D:\\a.exe'],['--one-archive=D:\\a.zip','--one-archive=D:\\b.zip'],['--one-archive=D:\\a\n.zip']])assert.throws(()=>archiveLaunchPath(args));
  const registry=spawnSync('powershell.exe',['-NoProfile','-NonInteractive','-ExecutionPolicy','Bypass','-File',path.resolve('tests/archive-associations.ps1'),'-Source',path.resolve('dist/main/archive-associations.ps1')],{encoding:'utf8',windowsHide:true});
  assert.equal(registry.status,0,registry.stdout+'\n'+registry.stderr);console.log(registry.stdout.trim());
  const input=path.join(root,'input');await fs.mkdir(input);
  const first=path.join(input,'双击 中文.txt'),second=path.join(input,'other.txt');
  await fs.writeFile(first,'Double click archive\n');await fs.writeFile(second,'Second source\n');
  const archive=path.join(root,'双击 智能.zip'),browse=path.join(root,'仅浏览.zip'),secret=path.join(root,'需要密码.zip'),queuedA=path.join(root,'连续一.zip'),queuedB=path.join(root,'连续二.zip');
  const create=(target,password='')=>{const bytes=Buffer.from(password),packet=Buffer.alloc(4+bytes.length);packet.writeUInt32LE(bytes.length);bytes.copy(packet,4);const result=spawnSync(path.resolve('dist/native/One.Archive.exe'),['create',target,first,second],{input:packet,encoding:'utf8',windowsHide:true});assert.equal(result.status,0,result.stdout+'\n'+result.stderr);};
  create(archive);create(browse);create(secret,'correct-password');create(queuedA);create(queuedB);
  const profile=path.join(root,'profile'),env={...process.env,ONE_TEST_MODE:'1',ONE_DATA_DIR:profile,TEMP:root,TMP:root};delete env.ELECTRON_RUN_AS_NODE;
  app=await electron.launch({args:[path.resolve('.'),`--one-archive=${archive}`],env});
  await app.evaluate(({shell})=>{globalThis.archiveExplorerCalls=0;shell.showItemInFolder=()=>globalThis.archiveExplorerCalls++;shell.openPath=async()=>{globalThis.archiveExplorerCalls++;return '';};});
  const page=await app.firstWindow(),errors=[];page.on('pageerror',error=>errors.push(String(error)));
  const tasks=()=>app.windows().filter(window=>/[?&]view=archive-task(?:$|&)/.test(window.url()));
  const task=async(count=1)=>{await expect.poll(()=>tasks().length,{timeout:20000}).toBe(count);const window=tasks().at(-1);await window.waitForSelector('#archive-task-feedback',{state:'attached'});return window;};
  const closeTask=async(window)=>{await window.locator('#archive-task-cancel').click({noWaitAfter:true});await expect.poll(()=>app.windows().includes(window)).toBe(false);};
  const initialTask=await task();await expect(initialTask.locator('#archive-task-feedback')).toContainText('已解压',{timeout:30000});
  assert.equal(await fs.readFile(path.join(root,'双击 智能','双击 中文.txt'),'utf8'),'Double click archive\n');
  await closeTask(initialTask);
  await page.evaluate(()=>window.one.patchSettings({archive:{doubleClick:'browse',defaultFormat:'7z'}}));
  await app.evaluate(({app},file)=>app.emit('second-instance',{},[process.execPath,`--one-archive=${file}`],process.cwd()),browse);
  await expect(page.locator('#archive-source')).toHaveValue(browse);
  await expect(page.locator('#archive-status-text')).toContainText('已读取',{timeout:20000});
  await assert.rejects(fs.stat(path.join(root,'仅浏览')),{code:'ENOENT'});
  await page.evaluate(()=>window.one.patchSettings({archive:{doubleClick:'smart'}}));
  await app.evaluate(({app},files)=>{for(const file of files)app.emit('second-instance',{},[process.execPath,`--one-archive=${file}`],process.cwd());},[queuedA,queuedB]);
  await expect.poll(()=>fs.readFile(path.join(root,'连续一','双击 中文.txt'),'utf8').catch(()=>null),{timeout:30000}).toBe('Double click archive\n');
  await expect.poll(()=>fs.readFile(path.join(root,'连续二','双击 中文.txt'),'utf8').catch(()=>null),{timeout:30000}).toBe('Double click archive\n');
  await expect.poll(()=>tasks().length).toBe(2);for(const window of tasks())await closeTask(window);
  await page.evaluate(file=>window.one.openFile(file),secret);
  const passwordTask=await task();await expect(passwordTask.locator('#archive-task-password-panel')).toBeVisible();
  await expect(passwordTask.locator('#archive-task-feedback')).not.toContainText('已解压');
  await assert.rejects(fs.stat(path.join(root,'需要密码')),{code:'ENOENT'});
  await passwordTask.locator('#archive-task-password').fill('correct-password');await passwordTask.locator('#archive-task-start').click();
  await expect(passwordTask.locator('#archive-task-feedback')).toContainText('已解压',{timeout:30000});
  assert.equal(await fs.readFile(path.join(root,'需要密码','双击 中文.txt'),'utf8'),'Double click archive\n');
  await closeTask(passwordTask);
  await page.evaluate(()=>localStorage.setItem('one-archive-open-completed','true'));
  await page.reload();await page.locator('[data-page="settings"]').click();await page.locator('[data-settings-tab="archive"]').click();
  await expect(page.locator('#archive-pref-open-completed')).toBeChecked();
  await expect(page.locator('#archive-pref-propagate-zone')).toBeChecked();
  await expect(page.locator('#archive-pref-scan')).not.toBeChecked();
  await page.locator('#archive-pref-scan').check();
  await expect.poll(()=>page.evaluate(async()=>(await window.one.settings()).archive.scanOnExtract)).toBe(true);
  await page.locator('#archive-pref-propagate-zone').uncheck();
  await expect.poll(()=>page.evaluate(async()=>(await window.one.settings()).archive.propagateZone)).toBe(false);
  assert.equal(await page.evaluate(()=>localStorage.getItem('one-archive-open-completed')),null);
  await expect(page.locator('#archive-association-toggle')).toBeDisabled();
  assert.equal(await page.locator('#archive-pref-format').evaluate(node=>node.value),'7z');
  await page.locator('#archive-pref-open-completed').uncheck();
  await expect.poll(async()=>JSON.parse(await fs.readFile(path.join(profile,'settings.json'),'utf8')).archive.openCompleted).toBe(false);
  await page.locator('[data-page="archive"]').click();
  await expect(page.locator('#archive-open-completed')).not.toBeChecked();
  assert.equal(await page.locator('#archive-format').evaluate(node=>node.value),'7z');
  await page.reload();await page.locator('[data-page="settings"]').click();await page.locator('[data-settings-tab="archive"]').click();
  await expect(page.locator('#archive-pref-propagate-zone')).not.toBeChecked();
  await expect(page.locator('#archive-pref-scan')).toBeChecked();
  assert.deepEqual(errors,[]);
  assert.equal(await app.evaluate(()=>globalThis.archiveExplorerCalls),0,'archive launches must not open Explorer');
  console.log('Archive launch smoke passed: smart startup, running-instance browse, queued requests, password recovery, settings migration and persistence.');
 }finally{if(app)await app.close();const relative=path.relative(path.resolve('work/temp'),root);assert(relative&&!relative.startsWith('..')&&!path.isAbsolute(relative));await fs.rm(root,{recursive:true,force:true});}
}
main().catch(error=>{console.error(error);process.exitCode=1;});
